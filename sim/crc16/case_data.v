//============================================================================
// case_data.v — 标准 Data CRC16 测试
//
// 测试目的: 验证 usb_crc16 对不同长度 payload 的正确性
//   用 crc16_ref.vh 参考模型实时计算期望值，无线硬编码黄金向量。
//
// 预期结果: 所有 payload 的余数和残差检查通过
//============================================================================

task case_data;
    begin
        $display("== case_data: standard CRC16 data vectors ==");

        // 5-byte 全零: 验证最小数据下的 CRC
        run_case(8'h00,8'h00,8'h00,8'h00,8'h00, 8'h00,8'h00,8'h00, 5);

        // 5-byte, 首字节 0x02: 验证非零起始
        run_case(8'h02,8'h00,8'h00,8'h00,8'h00, 8'h00,8'h00,8'h00, 5);

        // 8-byte, 首字节 0x80: 最大长度 + MSB set
        run_case(8'h80,8'h00,8'h00,8'h00,8'h00, 8'h00,8'h00,8'h00, 8);

        // 8-byte 递增: 0x00~0x07, 全 bit 翻转测试
        run_case(8'h00,8'h01,8'h02,8'h03,8'h04, 8'h05,8'h06,8'h07, 8);

        $display("  case_data done");
    end
endtask
