//============================================================================
// case_stuff_golden.v — 位填充器黄金向量测试
//
// 测试目的: 验证 usb_bit_stuff 在已知输入模式下的填充正确性
//   参考模型 bitstuff_ref.vh 实时检查 stuffed 0 的插入时机。
//
// 测试模式:
//   1. 6 个 1 → 插入 0
//   2. 7 个 1 → 插入 0 (6个后插0, 第7个正常)
//   3. 中间 6 个 1 → 插入 0
//   4. 第 6 个 1 在序列中段 → 插入 0
//   5. 两段 6 个 1 → 各插入 0
//
// 预期结果: 所有模式的填充输出位宽和位值匹配
//============================================================================

task case_stuff_golden;
    begin
        $display("== case_stuff_golden: stuffer golden vectors ==");

        // 输入 (MSB=第一个发送位)  期望填充输出
        check_stuff( 7'b1111110,        7,  8'b11111100,       8);   // 6个1→插0
        check_stuff( 7'b1111111,        7,  8'b11111101,       8);   // 7个1→插0
        check_stuff(12'b001111111100,   12, 13'b0011111101100, 13);  // 中间6个1
        check_stuff(13'b1011011111101,  13, 14'b10110111111001, 14); // 第6个1后插0
        check_stuff(14'b11111101111110, 14, 16'b1111110011111100, 16); // 两段6个1

        $display("  case_stuff_golden done");
    end
endtask
